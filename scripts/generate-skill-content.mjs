// Bundles skills/crochet-weaver-pattern/SKILL*.md into src/skill-content.ts.
//
// The settings tab copies the skill to the clipboard, and an installed plugin is
// just main.js — the Markdown files never ship with it. So the text is compiled
// in, and generated rather than kept in step by hand: `npm run generate-skill`
// after editing a SKILL file, which the build and the tests both run first.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// The languages the skill itself is written in. The plugin speaks more than
// these; the rest are handed the English one (see skillFor).
const SKILL_FILES = {
	en: 'skills/crochet-weaver-pattern/SKILL.md',
	'zh-TW': 'skills/crochet-weaver-pattern/SKILL.zh-TW.md',
	'zh-CN': 'skills/crochet-weaver-pattern/SKILL.zh-CN.md',
	ja: 'skills/crochet-weaver-pattern/SKILL.ja.md',
};

// The skill is Markdown full of backticks and ${}, so it goes in as an escaped
// template literal — the same way it reads on disk, byte for byte.
function asTemplateLiteral(text) {
	return `\`${text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')}\``;
}

const entries = Object.entries(SKILL_FILES)
	.map(([locale, path]) => {
		const key = locale.includes('-') ? `'${locale}'` : locale;
		return `\t${key}: ${asTemplateLiteral(readFileSync(resolve(root, path), 'utf8'))},`;
	})
	.join('\n');

const source = `// Generated by scripts/generate-skill-content.mjs from
// skills/crochet-weaver-pattern/SKILL*.md — edit those, then run
// \`npm run generate-skill\`. This is what the settings tab copies to the
// clipboard, bundled so it works offline (the Markdown files never ship with an
// installed plugin).
import type { Locale } from './i18n';

// The languages the skill has been written in. The plugin speaks more than
// these; anything else is handed the English one, which is the version an AI
// reads best anyway.
export type SkillLocale = Extract<Locale, ${Object.keys(SKILL_FILES)
	.map((locale) => `'${locale}'`)
	.join(' | ')}>;

export const SKILL_LOCALES: readonly SkillLocale[] = [${Object.keys(SKILL_FILES)
	.map((locale) => `'${locale}'`)
	.join(', ')}];

export const CROCHET_WEAVER_PATTERN_SKILL: Record<SkillLocale, string> = {
${entries}
};

export function patternSkill(locale: Locale): string {
	return CROCHET_WEAVER_PATTERN_SKILL[locale as SkillLocale] ?? CROCHET_WEAVER_PATTERN_SKILL.en;
}
`;

writeFileSync(resolve(root, 'src/skill-content.ts'), source);
console.log(`src/skill-content.ts written from ${Object.keys(SKILL_FILES).length} SKILL files`);
